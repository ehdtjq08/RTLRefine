"""Export actual studio runs, all earlier failures and the paired speed result."""
from pathlib import Path
import json
import shutil

from rtl_agent.common import ROOT,sha256,write_json


def main():
    target=ROOT/'demo/repair_studio';target.mkdir(exist_ok=False)
    def copy(source,destination):
        shutil.copytree(source,destination,ignore=lambda path,names:[n for n in names if n in ('obj_dir','__pycache__') or n.endswith(('.pyc','.o','.a','.vvp','.lock'))])
    cases={'overflow':'batch_repair_overflow_nebius_v3_20261023','length':'batch_repair_length_nebius_v1_20261023','reset':'batch_repair_reset_nebius_v1_20261023'}
    video=ROOT/'submission/studio-v1/video/validation.json'
    if video.exists():cases['overflow']=json.loads(video.read_text())['live_run_directory']
    for key,run in cases.items():copy(Path(run) if Path(run).is_absolute() else ROOT/'results'/run,target/key/'run')
    copy(ROOT/'results/batch_throughput_v1_20261023',target/'throughput')
    for run in ('batch_repair_overflow_nebius_v1_20261023','batch_repair_overflow_nebius_v2_20261023','batch_repair_overflow_local_v1_20261023'):
        copy(ROOT/'results'/run,target/'development_attempts'/run)
    (target/'MODIFICATIONS.md').write_text('''# Repair studio source and evidence

These three examples use the existing MIT-licensed, research-adapted historical
Verilog-axis defects and the unchanged V2 trace evaluator. Original/modified
source and source headers are retained with their case licenses. The research
artifact's BSD-3-Clause notice accompanies the evidence.

All candidates are generated by the project-authored finite source grammar.
NVIDIA Nemotron on Nebius diagnoses and prioritizes existing IDs. Trusted
screening instrumentation adds a runtime selector; that instrumented source is
never admitted as a repair. The final uninstrumented patch is separately built
and checked on all three fixed profiles. This is bounded golden-trace evidence,
not arbitrary RTL support, new upstream bug discovery or unbounded correctness.

The speed measurement covers the identical complete 118-candidate workload,
three public profiles, fresh build directories, inactive-output controls and
standalone compatibility fallbacks. It is one paired measurement per case on
this host; filesystem caches were not flushed. It measures screening throughput,
not model quality or end-to-end repair speed. Compiler-selector schemes have
prior art in mutation testing; no first-in-literature claim is made.

The three displayed runs are curated development examples. Earlier overflow
attempts remain in development_attempts, including a reasoning response that
hit its 12,288-token limit and a valid but wrong initial reset hypothesis whose
patches failed the public check. They are not excluded from a claimed accuracy
denominator because no population accuracy is claimed for these demo runs.
''')
    shutil.copyfile(ROOT/'research/known_bug_benchmark/ARTIFACT-LICENSE-BSD-3-Clause.txt',target/'ARTIFACT-LICENSE-BSD-3-Clause.txt')
    write_json(target/'manifest.json',{str(p.relative_to(target)):sha256(p.read_bytes()) for p in sorted(target.rglob('*')) if p.is_file()})
    print({'export':str(target),'files':sum(p.is_file() for p in target.rglob('*'))})


if __name__=='__main__':main()
